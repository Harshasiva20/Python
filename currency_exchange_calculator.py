# CURRENCY EXCHANGE CALCULATOR FROM USD AND GSBP TO INR

usd = float(input("Enter the USD amount:"))
gbp = float(input("Enter the GBP amount:"))

usd_to_inr = usd * 87
gbp_to_inr = gbp * 129

print(f"The INR value for USD {usd} is: {usd_to_inr}")

print(f"The INR value for GBP {gbp} is: {gbp_to_inr}")

